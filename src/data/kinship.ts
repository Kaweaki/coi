/**
 * The kinship model.
 *
 * Every relationship is a *path* of steps away from "you". Each step is
 * relative to the person before it, which is how Vietnamese actually works:
 * mẹ → em trai is "my mother's younger brother", not "my uncle".
 */

export type Step =
  | 'father'
  | 'mother'
  | 'husband'
  | 'wife'
  | 'son'
  | 'daughter'
  | 'elderBrother'
  | 'elderSister'
  | 'youngerBrother'
  | 'youngerSister'

