export const KIN_BY_ID: Record<string, Kin> = Object.fromEntries(
  KINSHIP.map((kin) => [kin.id, kin]),
)

export const pathKey = (path: Step[]): string => path.join('>')

/** Flat index: every path any entry can occupy. */
export const PATH_INDEX: Map<string, { kin: Kin; path: Step[] }> = (() => {
  const map = new Map<string, { kin: Kin; path: Step[] }>()
  for (const kin of KINSHIP) {
    for (const path of kin.paths) {
      map.set(pathKey(path), { kin, path })
    }
  }
  return map
})()

/** Longest known prefix of a path — used when a relation is unmapped. */
export function longestKnownPrefix(path: Step[]): { kin: Kin; path: Step[] } | null {
  for (let end = path.length - 1; end >= 1; end -= 1) {
    const hit = PATH_INDEX.get(pathKey(path.slice(0, end)))
    if (hit) return hit
  }
  return null
}
